/**
 * Generate a CodeWarrior-style derivative include file (e.g. `mc9s12xdp512.inc`) from a device description.
 *
 * Style (docs/research/r1/critique.md C6):
 *   PORTB:              equ       $00000001                                ;*** PORTB - Port B Register; 0x00000001 ***
 *               ; bit numbers for usage in BCLR, BSET, BRCLR, and BRSET
 *   PORTB_BIT0:         equ       0
 *               ; bit position masks
 *   mPORTB_BIT0:        equ       %00000001
 * plus memory-map equates (RAMStart/RAMEnd, ROM_C000Start, PAGE_E0Start, ...) and vector address equates (Vreset, ...).
 * CRLF line endings. Generated from data; not a copy of the NXP file.
 *
 * Register, byte-half and bit names follow CodeWarrior's own mc9s12xdp512 header (see registers.ts), e.g. PORTB_PB0,
 * TCNTHi, MCCNThi, TC0Hhi, CAN0RXTSRH; 16-bit composites (PORTAB, ATD0CTL23) carry the bits of both bytes.
 *
 * UNCERTAIN: exact column widths, comment texts, multi-bit field group equates (<REG>_<FIELD> = lsb position,
 * m<REG>_<FIELD> = mask), bit equates on composites, and the absence of the stock file's "DEPRECIATED SYMBOLS" block.
 */
import { fieldMask } from './bits.js';
import type { BitField, DeviceDescription, RegisterDef } from './types.js';

export interface IncOptions {
  /** Line terminator (default CRLF, like CodeWarrior's text files). */
  eol?: string;
  /** Emit bit-number and mask equates (default true). */
  bits?: boolean;
}

const NAME_COL = 20;
const EQU_COL = 10;
const VAL_COL = 41;

const hex8 = (n: number) => n.toString(16).toUpperCase().padStart(8, '0');
const bin = (n: number, digits: number) => n.toString(2).padStart(digits, '0');

function equLine(name: string, value: string, comment?: string): string {
  const head = `${name}:`.padEnd(NAME_COL - 1) + ' ' + 'equ'.padEnd(EQU_COL);
  if (!comment) return head + value;
  return head + value.padEnd(VAL_COL - 1) + ' ' + comment;
}

const regComment = (name: string, desc: string, addr: number) => `;*** ${name} - ${desc}; 0x${hex8(addr)} ***`;

const BIT_HEADER = '            ; bit numbers for usage in BCLR, BSET, BRCLR, and BRSET';
const MASK_HEADER = '            ; bit position masks';

class Emitter {
  readonly lines: string[] = [];
  private readonly seen = new Map<string, string>();

  constructor(private readonly withBits: boolean) {}

  raw(s = ''): void {
    this.lines.push(s);
  }

  sym(name: string, value: string, comment?: string): void {
    // The CW assembler is case-SENSITIVE unless -Ci is given (docs/research/r1/asm.md); we still reject names that
    // differ only in case so the file also assembles with -Ci.
    const key = name.toUpperCase();
    const prev = this.seen.get(key);
    if (prev !== undefined) throw new Error(`duplicate .inc symbol ${name} (already defined as ${prev})`);
    this.seen.set(key, name);
    this.lines.push(equLine(name, value, comment));
  }

  register(name: string, address: number, desc: string): void {
    this.sym(name, `$${hex8(address)}`, regComment(name, desc, address));
  }

  bits(reg: string, bits: readonly BitField[], digits: number): void {
    if (!this.withBits || bits.length === 0) return;
    this.raw(BIT_HEADER);
    for (const b of bits) this.sym(`${reg}_${b.name}`, String(b.bit));
    this.raw(MASK_HEADER);
    for (const b of bits) this.sym(`m${reg}_${b.name}`, `%${bin(fieldMask(b), digits)}`);
  }
}

/** Bits of one byte half of a 16-bit register, renumbered 7..0. Fields straddling the halves are dropped. */
function halfBits(bits: readonly BitField[], high: boolean): BitField[] {
  const lo = high ? 8 : 0;
  return bits
    .filter((b) => b.bit >= lo && b.bit + b.width <= lo + 8)
    .map((b) => ({ name: b.name, bit: b.bit - lo, width: b.width }));
}

const isDefaultData = (bits: readonly BitField[] | undefined) => !!bits && bits.every((b) => /^BIT\d+$/.test(b.name));

function emitRegister(e: Emitter, r: RegisterDef, skipHalves: Set<string>): void {
  e.register(r.name, r.address, r.description);
  if (r.size === 2 && r.halves) {
    const [h, l] = r.halves;
    if (!skipHalves.has(h)) e.register(h, r.address, `${r.description} High`);
    if (!skipHalves.has(l)) e.register(l, r.address + 1, `${r.description} Low`);
  }
  if (r.bits) e.bits(r.name, r.bits, r.size * 8);
  if (r.size === 2 && r.halves && r.bits && !isDefaultData(r.bits)) {
    const [h, l] = r.halves;
    if (!skipHalves.has(h)) e.bits(h, halfBits(r.bits, true), 8);
    if (!skipHalves.has(l)) e.bits(l, halfBits(r.bits, false), 8);
  }
}

export function generateIncFile(device: DeviceDescription, opts: IncOptions = {}): string {
  const eol = opts.eol ?? '\r\n';
  const e = new Emitter(opts.bits ?? true);
  const stars = ';' + '*'.repeat(78);

  e.raw(stars);
  e.raw(`;* ${device.name} register, memory-map and interrupt-vector definitions`);
  e.raw(`;* ${device.title}`);
  e.raw(';* Generated by S12 Studio (@s12/devices) from the device description; not an NXP file.');
  e.raw(';* Usage:  INCLUDE \'' + device.name.toLowerCase() + '.inc\'');
  e.raw(stars);
  e.raw();

  // Registers and aliases in address order (canonical first at a shared address).
  type Item = { r: RegisterDef; kind: 'canonical' | 'composite' | 'alternate' };
  const order = { canonical: 0, composite: 1, alternate: 2 } as const;
  const items: Item[] = [
    ...device.registers.map((r): Item => ({ r, kind: 'canonical' })),
    ...device.aliases.map((r): Item => ({ r, kind: r.composite ? 'composite' : 'alternate' })),
  ].sort((a, b) => a.r.address - b.r.address || order[a.kind] - order[b.kind]);
  const canonicalNames = new Set(device.registers.map((r) => r.name));

  e.raw(stars);
  e.raw(';* Registers');
  e.raw(stars);
  for (const { r, kind } of items) {
    if (kind === 'canonical') emitRegister(e, r, canonicalNames);
    else {
      e.register(r.name, r.address, r.description);
      if (r.bits) e.bits(r.name, r.bits, r.size * 8);
    }
    e.raw();
  }

  e.raw(stars);
  e.raw(';* Memory map (CodeWarrior logical addresses: local, or 0xPPAAAA for paged segments)');
  e.raw(stars);
  for (const s of device.segments) {
    e.sym(`${s.name}Start`, `$${hex8(s.start)}`);
    e.sym(`${s.name}End`, `$${hex8(s.end)}`);
  }
  e.raw();

  e.raw(stars);
  e.raw(';* Interrupt vector addresses (IVBR = $FF, the reset value)');
  e.raw(stars);
  for (const v of device.vectors) e.sym(v.name, `$${hex8(v.address)}`, `; ${v.source}`);
  e.raw();
  e.raw(';* end of file');

  return e.lines.join(eol) + eol;
}

/** Regexes that every generated line matches (documented style; used by tests and by the assembler package). */
export const INC_LINE_PATTERNS = {
  equ: /^([A-Za-z_][A-Za-z0-9_]*):\s+equ\s+(\$[0-9A-F]{8}|%[01]{8}|%[01]{16}|\d{1,2})(\s+;.*)?$/,
  register: /^([A-Za-z_][A-Za-z0-9_]*):\s+equ\s+\$([0-9A-F]{8})\s+;\*\*\* (\1) - .+; 0x(\2) \*\*\*$/,
  comment: /^\s*;.*$/,
  blank: /^$/,
} as const;
