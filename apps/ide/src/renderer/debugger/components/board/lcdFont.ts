/** Hollow box for characters without a drawn glyph (katakana etc.). */
const UNKNOWN = '#####|#...#|#...#|#...#|#...#|#...#|#####';

function parse(s: string): number[] {
  const rows = s.split('|').map((r) => [...r].reduce((v, c) => (v << 1) | (c === '#' ? 1 : 0), 0));
  while (rows.length < 8) rows.push(0);
  return rows;
}

const CACHE = new Map<string, number[]>();
const FULL = [0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f, 0x1f];

/** First private-use code point of CGRAM glyphs (matches @s12/sim CGRAM_BASE). */
export const CGRAM_BASE = 0xe000;

/** Characters that have a drawn glyph (tests, font preview). */
export const FONT_CHARS: readonly string[] = Object.keys(G);

/**
 * Dot rows for one LCD character. CGRAM characters (U+E000..U+E007) use `cgram` (8 rows x 5 bits); '█' is the
 * all-dots $FF block.
 */
export function glyphRows(ch: string, cgram?: readonly (readonly number[])[] | null): GlyphRows {
  const cp = ch.codePointAt(0) ?? 0x20;
  if (cp >= CGRAM_BASE && cp < CGRAM_BASE + 8) {
    const g = cgram?.[cp - CGRAM_BASE];
    return g ? Array.from({ length: 8 }, (_, i) => (g[i] ?? 0) & 0x1f) : parse(G[' ']);
  }
  if (ch === '█') return FULL;
  let rows = CACHE.get(ch);
  if (!rows) {
    rows = parse(G[ch] ?? UNKNOWN);
    CACHE.set(ch, rows);
  }
  return rows;
}

/** True if `ch` has a hand-drawn glyph (not the unknown box). */
export function hasGlyph(ch: string): boolean {
  const cp = ch.codePointAt(0) ?? 0;
  return ch in G || ch === '█' || (cp >= CGRAM_BASE && cp < CGRAM_BASE + 8);
}
